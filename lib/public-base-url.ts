export type PublicBaseUrl =
  | { state: "unset" | "invalid" }
  | { state: "local" | "configured"; url: string };

export function resolvePublicBaseUrl(raw: string | undefined): PublicBaseUrl {
  const value = raw?.trim();
  if (!value) return { state: "unset" };
  if (value.length > 2048 || !/^https?:\/\/[^/]/i.test(value) || /[\s\\@?#]/u.test(value)) return { state: "invalid" };
  let url: URL;
  try { url = new URL(value); } catch { return { state: "invalid" }; }
  if (url.username || url.password || !url.hostname) return { state: "invalid" };
  const host = url.hostname.replace(/\.$/, "");
  const local = host === "localhost" || host.endsWith(".localhost") ||
    host.startsWith("127.") && /^\d+(?:\.\d+){3}$/.test(host) ||
    host === "0.0.0.0" || host === "[::]" || host === "[::1]" ||
    /^\[::ffff:(?:7f[0-9a-f]{2}:[0-9a-f]+|0:0)\]$/.test(host);
  return { state: local ? "local" : "configured", url: url.origin + url.pathname.replace(/\/+$/, "") };
}

export function publicShareUrl(base: PublicBaseUrl, path: string): string | null {
  // Share paths are generated by Metis. Never resolve a caller-supplied origin.
  return base.state === "configured" && /^\/(?![/\\])/.test(path) ? base.url + path : null;
}

export function chatShareUrl(base: PublicBaseUrl, id: string) {
  return publicShareUrl(base, "/share?id=" + encodeURIComponent(id));
}

export function skillShareToken(value: string, currentOrigin: string, base: PublicBaseUrl) {
  if (/^[a-f0-9]{48}$/.test(value)) return value;
  const url = new URL(value, currentOrigin);
  const canonical = base.state === "configured" ? new URL(base.url) : null;
  const prefix = canonical?.pathname.replace(/\/$/, "") ?? "";
  const canonicalPath = canonical && url.origin === canonical.origin && url.pathname.startsWith(prefix + "/");
  if (url.username || url.password || (!canonicalPath && url.origin !== currentOrigin)) {
    throw new Error("Use a skill share link from this Metis workspace.");
  }
  const token = (path: string) => path.match(/^\/skills\/share\/([a-f0-9]{48})\/?$/)?.[1];
  return (canonicalPath ? token(url.pathname.slice(prefix.length)) : undefined) ||
    (url.origin === currentOrigin ? token(url.pathname) : undefined) || "";
}

export type PublicBaseCheck =
  | { state: "verified" | "unreachable" | "not_metis" | "other_instance" | "unsafe_url" | "https_required" }
  | { state: "redirect" | "http_error"; status: number }
  | Extract<PublicBaseUrl, { state: "unset" | "invalid" }>;

