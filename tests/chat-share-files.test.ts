import assert from "node:assert/strict";
import test from "node:test";
import {mkdtempSync,rmSync,writeFileSync} from "node:fs";
import os from "node:os";
import path from "node:path";
import {randomUUID} from "node:crypto";
import {publicMarkdownAssetUrl,publicMarkdownLinkTarget,publicMarkdownImageUrl} from "../lib/public-markdown";
const root=mkdtempSync(path.join(os.tmpdir(),"metis-shared-agent-files-"));
Object.assign(process.env,{CHAT_DATA_DIR:root,CHAT_DB_PATH:path.join(root,"chat.sqlite"),AI_CHAT_ROOT:root,AGENT_CWD:root});
test.after(()=>rmSync(root,{recursive:true,force:true}));

test("registered agent files work publicly, passwords stay scoped, and revocation closes downloads",async()=>{
 const auth=await import("../lib/auth"),db=await import("../lib/db-store"),uploads=await import("../lib/uploads");
 const jobs=await import("../lib/db-jobs"),{registerProvidedFile}=await import("../lib/provided-files");
 const shares=await import("../app/api/share/route"),files=await import("../app/api/share/attachment/route");
 const owner=auth.createUser("share-files-owner","synthetic-password");
 const chat=db.createChat("Provided report",undefined,owner.id),other=db.createChat("Other chat",undefined,owner.id);
 const messageId=randomUUID();db.appendMessage(chat.id,{id:messageId,role:"assistant",content:""},owner.id);
 const job=jobs.enqueueJob({chatId:chat.id,userId:owner.id,message:"Create report"});
 jobs.appendRunEvent(job.id,chat.id,owner.id,"assistantId",{messageId});
 const source=path.join(root,"report.txt");writeFileSync(source,"Provided report bytes");
 const attachment=await uploads.saveFileAttachment(chat.id,source,{name:"report.txt",mimeType:"text/plain"},owner.id);
 registerProvidedFile(chat.id,job.id,owner.id,attachment);
 const sourceUrl="/api/uploads/"+chat.id+"/"+attachment.storedName;
 db.upsertMessage(chat.id,{id:messageId,role:"assistant",content:"[Report]("+sourceUrl+")\n\n[Local file](workspace://file/%2Froot%2Fprivate.txt)"});
 let share=db.updateChatShare(chat.id,{active:true,content:{attachments:true}},owner.id)!.share!;
 const req=(name=attachment.storedName,cookie?:string,range?:string)=>new Request("http://test/api/share/attachment?id="+share.id+"&name="+encodeURIComponent(name),{headers:{...(cookie?{cookie}:{}),...(range?{range}:{})}});
 const publicChat=await(await shares.GET(new Request("http://test/api/share?id="+share.id))).json();
 assert.equal(publicChat.chat.messages[0].attachments[0].id,attachment.id);
 assert.equal(publicChat.chat.share.accessKey,undefined);
 const projected=publicChat.chat.assets[sourceUrl];
 const context={noteIds:[],assets:publicChat.chat.assets,chatShareId:share.id};
 assert.equal(publicMarkdownAssetUrl(sourceUrl,context),projected);
 assert.equal(publicMarkdownImageUrl("https://example.org/chart.png",context),"https://example.org/chart.png");
 assert.equal(publicMarkdownImageUrl("https://example.org/api/private/file",context),undefined);
 assert.equal(publicMarkdownLinkTarget("workspace://file/%2Froot%2Fprivate.txt",context),undefined);
 assert.equal(publicMarkdownAssetUrl(sourceUrl,{...context,chatShareId:"different"}),undefined);
 let response=await files.GET(req());assert.equal(response.status,200);assert.equal(await response.text(),"Provided report bytes");
 response=await files.GET(req(attachment.storedName,undefined,"bytes=0-7"));assert.equal(response.status,206);assert.equal(await response.text(),"Provided");
 assert.equal((await files.GET(req("../private.txt"))).status,404);
 const foreign=await uploads.saveFileAttachment(other.id,source,{name:"foreign.txt",mimeType:"text/plain"},owner.id);
 assert.equal((await files.GET(req(foreign.storedName))).status,404);
 share=db.updateChatShare(chat.id,{password:"view-secret"},owner.id)!.share!;
 assert.equal((await files.GET(req())).status,401);
 const unlock=await shares.POST(new Request("http://test/api/share",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({id:share.id,password:"view-secret"})}));
 assert.equal(unlock.status,200);
 const setCookie=unlock.headers.get("set-cookie")!;assert.match(setCookie,/HttpOnly/);assert.ok(!setCookie.includes("view-secret"));
 const cookie=setCookie.split(";")[0];
 response=await files.GET(req(attachment.storedName,cookie));assert.equal(response.status,200);assert.equal(await response.text(),"Provided report bytes");
 const otherShare=db.updateChatShare(other.id,{active:true,password:"view-secret"},owner.id)!.share!;
 const foreignResponse=await files.GET(new Request("http://test/api/share/attachment?id="+otherShare.id+"&name="+attachment.storedName,{headers:{cookie}}));
 assert.equal(foreignResponse.status,401);
 share=db.updateChatShare(chat.id,{content:{attachments:false}},owner.id)!.share!;
 assert.equal((await files.GET(req(attachment.storedName,cookie))).status,401);
 const hidden=db.getChatByShareId(share.id,"view-secret");
 assert.equal(hidden.status,"ok");if(hidden.status==="ok"){assert.deepEqual(hidden.chat.assets,{});assert.equal(hidden.chat.messages[0].attachments,undefined)}
 share=db.updateChatShare(chat.id,{active:false},owner.id)!.share!;
 assert.equal((await files.GET(req(attachment.storedName,cookie))).status,404);
 share=db.updateChatShare(chat.id,{active:true,content:{attachments:true}},owner.id)!.share!;
 assert.equal((await files.GET(req(attachment.storedName,cookie))).status,401,"old grant cannot survive stop/start");
});
